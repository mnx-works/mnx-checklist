#!/usr/bin/env python3
"""Generate the MNX v1.0 checklist from the notationref taxonomy.

Items come from concepts.json in w3c-cg/music-notationref. MNX support levels
come from docs/notationref.json in w3c/mnx. Every concept whose MNX entry says
"planned for 1.0" becomes a checklist item, grouped by the taxonomy's
group/subgroup hierarchy.

Usage:
    generate_checklist.py [--concepts PATH_OR_URL] [--mnx PATH_OR_URL] [-o OUT]

Checked boxes in an existing output file are preserved across regeneration.
"""

import argparse
import datetime
import json
import os
import re
import urllib.request

CONCEPTS_URL = "https://raw.githubusercontent.com/w3c-cg/music-notationref/main/concepts.json"
MNX_URL = "https://raw.githubusercontent.com/w3c/mnx/main/docs/notationref.json"
PLANNED_MARKER = "planned for 1.0"


def load_json(source):
    if re.match(r"https?://", source):
        with urllib.request.urlopen(source) as response:
            return json.load(response)
    with open(source, encoding="utf-8") as f:
        return json.load(f)


def read_checked_ids(path):
    if not os.path.exists(path):
        return set()
    checked = set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"\s*- \[[xX]\] .*`([^`]+)`\s*$", line)
            if m:
                checked.add(m.group(1))
    return checked


def collect(node, support, path, out):
    """Append (path, item) for each planned item under node, in taxonomy order."""
    if node["type"] == "item":
        entry = support.get(node["id"])
        if entry and PLANNED_MARKER in entry.get("text", ""):
            out.append((tuple(path), node))
        return
    for child in node.get("items", []):
        collect(child, support, path + [node["name"]], out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--concepts", default=CONCEPTS_URL)
    parser.add_argument("--mnx", default=MNX_URL)
    parser.add_argument("-o", "--output", default=os.path.join(here, "CHECKLIST.md"))
    args = parser.parse_args()

    concepts = load_json(args.concepts)
    support = load_json(args.mnx)["support"]
    checked = read_checked_ids(args.output)

    planned = []
    for group in concepts:
        collect(group, support, [], planned)

    lines = [
        "# MNX v1.0 remaining work",
        "",
        "Generated by `generate_checklist.py` on "
        f"{datetime.date.today().isoformat()} from the "
        "[notationref](https://w3c-cg.github.io/music-notationref/) taxonomy. "
        f"Each item is a concept that MNX's `docs/notationref.json` marks as "
        f"\"{PLANNED_MARKER}\". Checked boxes survive regeneration.",
        "",
        f"**{len(planned)} items** "
        f"({sum(1 for _, item in planned if item['id'] in checked)} checked)",
        "",
    ]

    group_counts = {}
    for path, _ in planned:
        group_counts[path[0]] = group_counts.get(path[0], 0) + 1

    lines.append("## Summary")
    lines.append("")
    lines.append("| Group | Items |")
    lines.append("| --- | ---: |")
    for group, count in group_counts.items():
        lines.append(f"| {group} | {count} |")
    lines.append("")

    current_group = None
    current_sub = None
    for path, item in planned:
        if path[0] != current_group:
            current_group = path[0]
            current_sub = None
            lines.append(f"## {current_group}")
            lines.append("")
        sub = " › ".join(path[1:])
        if sub and sub != current_sub:
            current_sub = sub
            lines.append(f"### {sub}")
            lines.append("")
        mark = "x" if item["id"] in checked else " "
        lines.append(f"- [{mark}] {item['name']} `{item['id']}`")
    lines.append("")

    # Blank lines between subgroups: insert one before each ### or ## that follows a list item.
    text = "\n".join(lines)
    text = re.sub(r"(`\n)(#{2,3} )", r"\1\n\2", text)

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Wrote {len(planned)} items to {args.output}")


if __name__ == "__main__":
    main()
